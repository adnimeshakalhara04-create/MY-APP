const unitSelect=$('#unitSelect'),sideSelect=$('#sideSelect'),sizePreset=$('#sizePreset'),searchInput=$('#searchInput'),cardGrid=$('#cardGrid'),summary=$('#unitSummary'),count=$('#heroCount'),empty=$('#emptyState'),customSize=$('#customSize'),widthInput=$('#cardWidth'),heightInput=$('#cardHeight');

units.forEach(u=>{const o=document.createElement('option');o.value=u.id;o.textContent=`Unit ${u.id}`;unitSelect.appendChild(o)});

function escapeHtml(value){return String(value).replace(/[&<>'"]/g,ch=>({'&':'&amp;','<':'&lt;','>':'&gt;',"'":'&#39;','"':'&quot;'}[ch]))}
function answerHtml(value){return escapeHtml(value).replace(/\n/g,'<br>')}
function cardId(unit,index){return `${unit.id}-${String(index+1).padStart(3,'0')}`}
function applyUnitTheme(unit){document.documentElement.style.setProperty('--unit',unit.color);document.documentElement.style.setProperty('--unit-soft',unit.soft)}
function currentUnit(){return units.find(u=>u.id===unitSelect.value)||units[0]}
function render(){
  const unit=currentUnit();applyUnitTheme(unit);
  const query=searchInput.value.trim().toLowerCase();
  const filtered=unit.cards.map((c,i)=>({c,i})).filter(({c})=>!query||`${c[0]} ${c[1]}`.toLowerCase().includes(query));
  count.textContent=filtered.length;
  summary.innerHTML=`<div><h2>Unit ${unit.id} — ${escapeHtml(unit.title)}</h2><p>${unit.cards.length} cards • print size: ${getSizeLabel()}</p></div><span class="unit-chip">UNIT ${unit.id}</span>`;
  cardGrid.innerHTML=filtered.map(({c,i})=>`<article class="flash-card"><div class="card-stripe"></div><div class="card-top"><span class="unit-label">UNIT ${unit.id}</span><span class="card-number">${cardId(unit,i)}</span></div><div class="card-content"><div class="question-wrap"><div class="side-label">FRONT • ප්‍රශ්නය</div><p class="question">${escapeHtml(c[0])}</p></div><div class="answer-wrap"><div class="side-label">BACK • පිළිතුර</div><div class="answer">${answerHtml(c[1])}</div></div></div><div class="card-footer">ET Revision Card • ${cardId(unit,i)}</div></article>`).join('');
  empty.hidden=filtered.length>0;
}

function getDimensions(){
  const preset=sizePreset.value;
  if(preset==='small')return[70,45];
  if(preset==='large')return[100,65];
  if(preset==='custom')return[clamp(+widthInput.value,55,120,85),clamp(+heightInput.value,35,90,55)];
  return[85,55];
}
function clamp(value,min,max,fallback){return Number.isFinite(value)?Math.min(max,Math.max(min,value)):fallback}
function applySize(){const [w,h]=getDimensions();document.documentElement.style.setProperty('--card-w',`${w}mm`);document.documentElement.style.setProperty('--card-h',`${h}mm`);render()}
function getSizeLabel(){const [w,h]=getDimensions();return `${w} × ${h} mm`}

